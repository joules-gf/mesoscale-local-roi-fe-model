from abaqus import *
from abaqusConstants import *
from odbAccess import openOdb
import csv
import os
import sys

def Get_Force_Disp(odb_file, node_set1, node_set2):
#odb_directory = os.getcwd()

    csv_name = "{}.csv".format(odb_file)

    results = []
    results.append(["ODB file name: {}".format(odb_file)])
    results.append(["Step Time", "U_Y", "Total RF Y", "Bottom RF Node Count", "Upper U Node Count"])
    odb = openOdb(path="{}.odb".format(odb_file))
    step = odb.steps['Step-1']
    instance = odb.rootAssembly.instances['I-PART-1']

    bottom_set_region = instance.nodeSets[node_set1]
    upper_set_region = instance.nodeSets[node_set2]

    for frame in step.frames:
        step_time = frame.frameValue
        rf = frame.fieldOutputs['RF'].getSubset(region=bottom_set_region)
        u = frame.fieldOutputs['U'].getSubset(region=upper_set_region)

        rf_y = 0.0
        for rf_val in rf.values:
            rf_data = -1 * rf_val.data
            rf_y += rf_data[1]

        disp_y = 0.0
        for u_val in u.values:
            u_data = u_val.data
            disp_y += u_data[1]

        if len(u.values) > 0:
            avg_disp_y = disp_y / float(len(u.values))
        else:
            avg_disp_y = 0.0

        results.append([step_time, avg_disp_y, rf_y, len(rf.values), len(u.values)])

    odb.close()

    # Write CSV

    # Go up two levels
    target_dir = os.path.dirname(os.getcwd())
    csv_file_output_dir = os.path.join(target_dir, csv_name)

    open_kwargs = {"newline": ""} if sys.version_info[0] >= 3 else {}
    with open(csv_file_output_dir, 'w', **open_kwargs) as csvfile:
        writer = csv.writer(csvfile)
        writer.writerows(results)


def _default_odb_file():
    odb_files = [name for name in os.listdir(os.getcwd()) if name.lower().endswith(".odb")]
    if len(odb_files) == 1:
        return os.path.splitext(odb_files[0])[0]
    raise RuntimeError("Set ODB_FILE or run from a directory containing exactly one .odb file")


if __name__ == "__main__":
    # Abaqus/CAE launched from WSL/Windows can sanitize environment variables,
    # so fall back to the single ODB in the working directory and the node-set
    # names generated by the input writer.
    odb_file = os.environ.get("ODB_FILE") or _default_odb_file()
    node_set1 = os.environ.get("BOTTOMNODES", "BOTTOMNODES")
    node_set2 = os.environ.get("UPPERNODES", "UPPERNODES")

    Get_Force_Disp(odb_file, node_set1, node_set2)
